"""
CERT-In Compliance Report Generator.
Generates structured Markdown incident disclosure reports compliant with
CERT-In Directions 2022 (6-hour mandatory reporting) and DPDP Act 2023.
"""

import time
from typing import List, Optional
from certin_sentinel.core.classifier import TriagedIncident, DPDPClassification


class CertInReportGenerator:
    """Generates CERT-In format Markdown incident reports."""

    def generate(self, incident: TriagedIncident, organization_name: str = "GrooveXlabs") -> str:
        now = time.strftime("%Y-%m-%d %H:%M:%S IST", time.localtime())
        deadline = time.strftime(
            "%Y-%m-%d %H:%M:%S IST",
            time.localtime(time.time() + (incident.reporting_deadline_hours * 3600))
        )

        technique_rows = ""
        for t in incident.mapped_techniques:
            technique_rows += f"| `{t.technique_id}` | {t.name} | {t.tactic} | {t.severity} |\n"
        if not technique_rows:
            technique_rows = "| — | No MITRE techniques mapped | — | — |\n"

        ioc_lines = ""
        for ioc in incident.indicators_of_compromise:
            ioc_lines += f"- `{ioc}`\n"
        if not ioc_lines:
            ioc_lines = "- None identified at this time\n"

        evidence_lines = ""
        for h in incident.evidence_hashes:
            evidence_lines += f"- `{h}`\n"
        if not evidence_lines:
            evidence_lines = "- No evidence files hashed yet\n"

        action_lines = ""
        for i, action in enumerate(incident.recommended_actions, 1):
            action_lines += f"{i}. {action}\n"

        affected_lines = ""
        for sys in incident.affected_systems:
            affected_lines += f"- {sys}\n"

        dpdp_section = ""
        if incident.dpdp_classification != DPDPClassification.NOT_APPLICABLE:
            dpdp_section = f"""
---

## 📋 DPDP Act 2023 — Data Breach Notification

| Field | Value |
| :--- | :--- |
| **Classification** | `{incident.dpdp_classification.value}` |
| **Obligation** | Notify Data Protection Board of India without unreasonable delay |
| **Data Principal Notification** | Required under Section 8(5) of DPDP Act 2023 |
| **Recommended Timeline** | Within 72 hours of becoming aware of the breach |

> [!CAUTION]
> This incident involves personal data of Indian data principals.
> Failure to report may result in penalties up to ₹250 Crore under DPDP Act 2023.
"""

        report = f"""# 🚨 CERT-In Incident Report

> **Generated by CERT-In Sentinel v0.1.0 — GrooveXlabs Sovereign Defense Ecosystem**
> **Report Time:** {now}

---

## 1. Incident Summary

| Field | Value |
| :--- | :--- |
| **Incident ID** | `{incident.incident_id}` |
| **Title** | {incident.title} |
| **Category** | {incident.category.value} |
| **Severity** | **{incident.severity.value}** |
| **DPDP Classification** | {incident.dpdp_classification.value} |
| **Report Generated** | {now} |
| **Reporting Deadline** | ⏰ **{deadline}** (6 hours from detection) |
| **Organization** | {organization_name} |

### Description
{incident.summary}

---

## 2. Affected Systems

{affected_lines}

---

## 3. MITRE ATT&CK Mapping

| Technique ID | Name | Tactic | Severity |
| :--- | :--- | :--- | :--- |
{technique_rows}

---

## 4. Indicators of Compromise (IOCs)

{ioc_lines}

---

## 5. Evidence Chain-of-Custody (SHA-256 Hashes)

{evidence_lines}

---

## 6. Recommended Immediate Actions

{action_lines}
{dpdp_section}
---

## 📌 CERT-In Reporting Reference

- **Reporting Portal:** [https://www.cert-in.org.in/](https://www.cert-in.org.in/)
- **Email:** incident@cert-in.org.in
- **Mandatory Reporting Deadline:** 6 hours from time of detection (CERT-In Directions, April 2022)
- **Legal Basis:** Information Technology Act 2000, Section 70B; CERT-In Directions 2022; DPDP Act 2023

---

*This report was generated offline by CERT-In Sentinel. Zero data was transmitted externally.*
*All analysis was performed locally on sovereign infrastructure.*
"""
        return report.strip()
